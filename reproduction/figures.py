#!/usr/bin/env python3
"""Snapshot and render the paper's existing figure notebooks in isolation.

This reproduces the figure inputs as supplied; it does not validate that those
inputs are measured results. See PROVENANCE.md before using a rendered figure.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = Path(__file__).resolve().parent
SNAPSHOT = PACKAGE / 'figure_inputs'

FIGURES = {
    'fig1': ('fig1-PerpvsLoadedKV', 'plot_ppl_vs_loaded_kv.ipynb', ['TopP_ppl_KVamp.xlsx']),
    'fig2': ('fig2-KV-Amplification', 'plot_union_amp_vs_topp.ipynb', []),
    'fig4': ('fig4-KVvsScore', 'plot_llama_kv_vs_score.ipynb', ['LLaMa_KV_Score.md']),
    'fig5': ('fig5-Passkey-KV减少', 'plot_passkey_retained_reduced.ipynb', ['ressum.md']),
    'fig6': ('fig6-kernel speedup/SparseAttenKernel', 'sparse_attention_kernel.ipynb', ['Qasper_Rate08_FI_Summary.md', 'GAS_Custom_Fused_Kernel_Technical_Handoff_20261114.md']),
    'fig7': ('fig7-TPOT result/NewEnv', 'TPOT_Speedup.ipynb', ['Qasper_Rate08_Tuned_TPOT_Projection.md']),
    'fig8': ('fig8-TimeBreakdown', 'TimeBreakdown.ipynb', ['README.md', 'time_breakdown_data.csv']),
    'fig8_backup': ('fig8-TimeBreakdown/bk_tested', 'TimeBreakdown.ipynb', ['实验记录.md', 'time_breakdown_data.csv']),
}

# Presentation-only assets cannot be regenerated by the numerical notebooks.
STATIC = [
    'fig3-GAS-Overview/GAS-Frame.pptx',
    'fig3-GAS-Overview/GAS-Frame_new.pdf',
    'fig1-PerpvsLoadedKV/论文组合图/top_k_top_p_motivation.pptx',
    'fig1-PerpvsLoadedKV/论文组合图/top_k_top_p_motivation.pdf',
    'fig2-KV-Amplification/组合绘图/gqa_union_amplification_combined.pptx',
    'fig2-KV-Amplification/组合绘图/gqa_union_amplification_combined.pdf',
    'tab2-Accuracy/dataTest.md',
]


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def source_paths():
    paths = set(STATIC)
    for directory, notebook, inputs in FIGURES.values():
        paths.add(str(Path(directory) / notebook))
        paths.update(str(Path(directory) / name) for name in inputs)
    return sorted(paths)


def snapshot():
    if SNAPSHOT.exists():
        raise FileExistsError(f'{SNAPSHOT} already exists; refusing to overwrite snapshot')
    missing = [name for name in source_paths() if not (ROOT / 'Figures' / name).is_file()]
    if missing:
        raise FileNotFoundError(f'missing figure sources: {missing}')
    SNAPSHOT.mkdir(parents=True)
    entries = []
    for name in source_paths():
        src, dst = ROOT / 'Figures' / name, SNAPSHOT / name
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        entries.append({'path': name, 'sha256': digest(dst), 'bytes': dst.stat().st_size})
    (SNAPSHOT / 'manifest.json').write_text(json.dumps({'files': entries}, indent=2, ensure_ascii=False) + '\n')
    print(f'Snapshotted {len(entries)} files into {SNAPSHOT}')


def verify():
    manifest = json.loads((SNAPSHOT / 'manifest.json').read_text())
    failures = []
    for entry in manifest['files']:
        path = SNAPSHOT / entry['path']
        if not path.is_file() or digest(path) != entry['sha256']:
            failures.append(entry['path'])
    if failures:
        raise ValueError(f'figure snapshot missing or changed: {failures}')
    print(f'Verified {len(manifest["files"])} snapshot files')


def render_one(name: str, destination: Path):
    directory, notebook_name, inputs = FIGURES[name]
    with tempfile.TemporaryDirectory(prefix=f'gas_{name}_') as temp:
        root = Path(temp)
        if name == 'fig5':
            # Preserve the notebook's original project-relative layout in a sandbox.
            plot_dir = root / '会用到的论文图与复现/fig4b-Passkey-KV减少'
            marker = root / 'Paper/DAC2027/Figures/source/build_experiment_figures.py'
            marker.parent.mkdir(parents=True)
            marker.touch()
            cwd = root
        else:
            plot_dir = root / Path(directory).name
            cwd = plot_dir
        plot_dir.mkdir(parents=True, exist_ok=True)
        for item in [notebook_name, *inputs]:
            shutil.copy2(SNAPSHOT / directory / item, plot_dir / item)
        notebook_path = plot_dir / notebook_name
        notebook = json.loads(notebook_path.read_text(encoding='utf-8'))
        namespace = {'__name__': '__main__', '__file__': str(notebook_path)}
        old_cwd = Path.cwd()
        os.chdir(cwd)
        try:
            for index, cell in enumerate(notebook['cells']):
                if cell['cell_type'] != 'code':
                    continue
                lines = cell['source']
                # The notebooks only use IPython magics to configure display.
                source = ''.join(line for line in lines if not line.lstrip().startswith('%'))
                print(f'{name}: executing cell {index}', flush=True)
                exec(compile(source, f'{notebook_path}:cell{index}', 'exec'), namespace)
        finally:
            os.chdir(old_cwd)
        generated = [p for p in root.rglob('*') if p.is_file() and p.suffix.lower() in ('.pdf', '.png')]
        if not generated:
            raise RuntimeError(f'{name} generated no PDF or PNG')
        destination.mkdir(parents=True, exist_ok=True)
        for src in generated:
            # Different destinations may have the same name, e.g. fig5's paper copy.
            target = destination / src.relative_to(root)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, target)
        for src in root.rglob('time_breakdown_data.csv'):
            if src.parent == plot_dir:
                shutil.copy2(src, destination / 'rendered_time_breakdown_data.csv')
        print(f'{name}: wrote {len(generated)} figure files to {destination}', flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='command', required=True)
    sub.add_parser('snapshot')
    sub.add_parser('verify')
    draw = sub.add_parser('render')
    draw.add_argument('--figures', nargs='+', choices=[*FIGURES, 'all'], default=['all'])
    draw.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    if args.command == 'snapshot':
        snapshot()
    elif args.command == 'verify':
        verify()
    else:
        verify()
        output = args.output.resolve()
        if output == SNAPSHOT or SNAPSHOT in output.parents or output == ROOT / 'Figures' or ROOT / 'Figures' in output.parents:
            raise ValueError('render output must not be inside the figure inputs or original Figures directory')
        if output.exists() and any(output.iterdir()):
            raise FileExistsError(f'refusing to overwrite nonempty output directory: {output}')
        os.environ.setdefault('MPLBACKEND', 'Agg')
        names = list(FIGURES) if args.figures == ['all'] else args.figures
        if 'all' in names:
            parser.error('use all alone, or a list of individual figures')
        for name in names:
            render_one(name, output / name)


if __name__ == '__main__':
    main()
